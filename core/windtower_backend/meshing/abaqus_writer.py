from __future__ import annotations

from pathlib import Path
from typing import Any

from .models import MeshResult, TowerMeshInput


def write_mesh_inp(path: Path, result: MeshResult, tower: list[TowerMeshInput], part_name: str = "WINDTOWER_SHELL_MESH") -> None:
    by_segment: dict[int, list[int]] = {}
    for eid, seg_id in result.element_segments.items():
        by_segment.setdefault(seg_id, []).append(eid)
    with path.open("w", encoding="utf-8") as f:
        f.write("*Heading\n")
        f.write(f"** Mesh-only include generated by {result.strategy}\n")
        f.write(f"*Part, name={part_name}\n")
        f.write("*Node\n")
        for nid in sorted(result.nodes):
            x, y, z = result.nodes[nid]
            f.write(f"{nid}, {x:.6f}, {y:.6f}, {z:.6f}\n")
        f.write("*Element, type=S4R\n")
        for eid in sorted(result.elements):
            f.write(f"{eid}, " + ", ".join(str(nid) for nid in result.elements[eid]) + "\n")
        _write_elset(f, "ALL_ELEMENTS", sorted(result.elements))
        for seg_id, values in sorted(by_segment.items()):
            _write_elset(f, f"SEG_{seg_id:03d}", values)
        for name in ("DOOR_PATCH_ELEMENTS", "DOOR_NEIGHBOR_ELEMENTS"):
            _write_elset(f, name, result.sets.get(name, []))
        for seg_id, values in sorted(by_segment.items()):
            thickness = tower[seg_id - 1].thickness_mm
            f.write(f"*Shell Section, elset=SEG_{seg_id:03d}, material=STEEL\n")
            f.write(f"{thickness:.6f}, 5\n")
        f.write("*End Part\n")


def _write_elset(f: Any, name: str, values: Any) -> None:
    f.write(f"*Elset, elset={name}\n")
    _write_wrapped(f, values)


def _write_wrapped(f: Any, values: Any, per_line: int = 16) -> None:
    values = sorted(set(values))
    for i in range(0, len(values), per_line):
        f.write(", ".join(str(v) for v in values[i : i + per_line]) + "\n")
